"""Build the Windows one-file executable with an isolated native DLL search path."""

from __future__ import annotations

import importlib.metadata
import os
import re
import runpy
import sys
from pathlib import Path


PROJECT_DIR = Path(__file__).resolve().parent
SYSTEM_ROOT = Path(os.environ.get("SystemRoot", r"C:\Windows"))
WORK_DIR = PROJECT_DIR / "build" / "pyinstaller"
LOCK_FILE = PROJECT_DIR / "requirements.lock"
VERSION_FILE = PROJECT_DIR / "command_center" / "__init__.py"
TOC_PATH = WORK_DIR / "CommandCenter" / "EXE-00.toc"
EXE_PATH = PROJECT_DIR / "dist" / "CommandCenter.exe"

# Qt components the application never imports. PySide6 ships them as plugins or
# companion libraries, so they are removed from the bundle by file name. Qt
# Virtual Keyboard is GPLv3/commercial only and Qt PDF needs its own licence
# choice, so neither should travel inside the LGPL-based executable.
EXCLUDED_BUNDLE_TOKENS = ("virtualkeyboard", "qt6pdf", "qtpdf", "qpdf")

SPEC_TEMPLATE = '''\
# Generated by build_exe.py on every build. Do not edit or commit.
from PyInstaller.building.api import EXE, PYZ
from PyInstaller.building.build_main import Analysis

EXCLUDED_TOKENS = {tokens!r}


def keep(entry):
    name = str(entry[0]).replace("\\\\", "/").lower()
    return not any(token in name for token in EXCLUDED_TOKENS)


a = Analysis(
    [{main!r}],
    pathex=[{project!r}],
    binaries=[],
    datas={datas!r},
    hiddenimports=[],
    hookspath=[],
    runtime_hooks=[],
    excludes=[],
    noarchive=False,
)
a.binaries = [entry for entry in a.binaries if keep(entry)]
a.datas = [entry for entry in a.datas if keep(entry)]
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name="CommandCenter",
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    console=False,
    icon=[{icon!r}],
)
'''


def write_spec() -> Path:
    """Write the PyInstaller spec that drops the excluded Qt components."""
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    spec_path = WORK_DIR / "CommandCenter.spec"
    spec_path.write_text(
        SPEC_TEMPLATE.format(
            tokens=EXCLUDED_BUNDLE_TOKENS,
            main=str(PROJECT_DIR / "main.py"),
            project=str(PROJECT_DIR),
            datas=[
                (str(PROJECT_DIR / "app_icon.ico"), "."),
                (str(PROJECT_DIR / "LICENSE"), "."),
                (str(PROJECT_DIR / "licenses"), "licenses"),
            ],
            icon=str(PROJECT_DIR / "app_icon.ico"),
        ),
        encoding="utf-8",
    )
    return spec_path


def check_version_consistency() -> None:
    """Stop the build if the package version cannot be read."""
    match = re.search(r'__version__\s*=\s*"([^"]+)"', VERSION_FILE.read_text(encoding="utf-8"))
    if match is None:
        raise SystemExit("No se encontró __version__ en command_center/__init__.py")


def normalize_name(name: str) -> str:
    return name.lower().replace("_", "-")


def check_locked_versions() -> None:
    """Stop the build if the installed packages differ from requirements.lock."""
    locked: dict[str, str] = {}
    for line in LOCK_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "==" in line:
            name, version = line.split("==", 1)
            locked[normalize_name(name)] = version.strip()

    mismatches = []
    for name, expected in sorted(locked.items()):
        try:
            installed = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            installed = "no instalado"
        if installed != expected:
            mismatches.append(f"{name}: instalado {installed}, lock {expected}")
    if mismatches:
        raise SystemExit(
            "Las dependencias no coinciden con requirements.lock:\n  "
            + "\n  ".join(mismatches)
            + "\nInstala las versiones exactas con: python -m pip install -r requirements.lock"
        )


def verify_bundle() -> None:
    """Fail the build, and remove its executable, if an excluded Qt component reached it."""
    if not TOC_PATH.is_file():
        raise SystemExit(f"No se encontró la tabla de contenido del build: {TOC_PATH}")
    toc = TOC_PATH.read_text(encoding="utf-8", errors="replace").lower()
    found = [token for token in EXCLUDED_BUNDLE_TOKENS if token in toc]
    if found:
        EXE_PATH.unlink(missing_ok=True)
        raise SystemExit(
            "El ejecutable incluye componentes excluidos (" + ", ".join(found)
            + "). Se eliminó dist\\CommandCenter.exe."
        )


def main() -> None:
    """Run PyInstaller without unrelated directories inherited on PATH."""
    check_version_consistency()
    check_locked_versions()
    python_dir = Path(sys.executable).resolve().parent
    os.environ["PATH"] = os.pathsep.join(
        str(path) for path in (SYSTEM_ROOT / "System32", SYSTEM_ROOT, python_dir)
    )
    os.chdir(PROJECT_DIR)
    spec_path = write_spec()
    sys.argv = [
        "PyInstaller", "--noconfirm", "--clean",
        "--distpath", str(PROJECT_DIR / "dist"),
        "--workpath", str(WORK_DIR),
        str(spec_path),
    ]
    try:
        runpy.run_module("PyInstaller", run_name="__main__")
    except SystemExit as exit_request:
        if exit_request.code not in (None, 0):
            raise
    verify_bundle()


if __name__ == "__main__":
    main()
